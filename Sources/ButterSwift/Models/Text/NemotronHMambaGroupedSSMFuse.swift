        device float *h [[buffer(5)]],
        device half *y [[buffer(6)]],
        constant uint &head_dim [[buffer(7)]],
        constant uint &state_dim [[buffer(8)]],
        constant uint &heads_per_group [[buffer(9)]],
        uint3 gid [[thread_position_in_grid]]
    ) {
        uint v_idx = gid.x;
        auto v1 = head_dim;
        auto v_h_id = v_idx / v1;
        auto v3 = v_h_id * v1;
        auto v_d = v_idx - v3;
