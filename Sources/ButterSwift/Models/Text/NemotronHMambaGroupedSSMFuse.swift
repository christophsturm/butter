    /// Replaces `nGroups` calls to `Ops.ssmStep` (one per group, each
    /// operating on a host-sliced sub-view) with ONE dispatch spanning
    /// every `(head, channel)` pair. `x`/`a`/`dt`/`state h`/`into y`
    /// are the FULL, unsliced tensors (shape `[nHeads*headDim]` /
    /// `[nHeads]` / `[nHeads*stateDim*headDim]`); `b`/`c` are the FULL
    /// `[nGroups*stateDim]` tensors (i.e. `bAll`/`cAll` reshaped flat,
    /// NOT sliced to one group). `nHeads` must be a multiple of
    /// `headsPerGroup`.
    static func ssmStepGrouped(
        x: Tensor, a: Tensor, b: Tensor, c: Tensor, dt: Tensor,
        state h: Tensor, into y: Tensor,
        nHeads: Int, headDim: Int, stateDim: Int, headsPerGroup: Int,
        on cmd: MTLCommandBuffer, device: Device
    ) {
        precondition(h.dtype == .f32, "NemotronHMambaGroupedSSMFuse.ssmStepGrouped: state h must be f32")
        precondition(x.dtype == y.dtype, "NemotronHMambaGroupedSSMFuse.ssmStepGrouped: x and y dtype must match")
        precondition(
            a.dtype == x.dtype && b.dtype == x.dtype
                && c.dtype == x.dtype && dt.dtype == x.dtype,
            "NemotronHMambaGroupedSSMFuse.ssmStepGrouped: a/b/c/dt dtype must match x")
        precondition(
            headsPerGroup > 0 && nHeads % headsPerGroup == 0,
            "NemotronHMambaGroupedSSMFuse.ssmStepGrouped: nHeads must be a multiple of headsPerGroup")
        let name: String
        switch x.dtype {
        case .f32: name = "nemotron_mixer_ssm_step_grouped_f32"
        case .f16: name = "nemotron_mixer_ssm_step_grouped_f16"
        case .bf16: name = "nemotron_mixer_ssm_step_grouped_bf16"
        default: fatalError("NemotronHMambaGroupedSSMFuse.ssmStepGrouped: unsupported dtype \(x.dtype)")
        }
        // Matches iron's own default fast-math (see file header) —
        // needed so the compiled arithmetic reproduces `iron_ssm_step`
        // bit-for-bit; verified in `NemotronHMambaGroupedSSMFuseTests`.
        let p = pso(name, source: ssmStepGroupedSrc, device: device.mtlDevice, fastMath: true)
        guard let enc = cmd.makeComputeCommandEncoder() else { return }
        enc.setComputePipelineState(p)
        enc.setBuffer(x.buffer, offset: x.offset, index: 0)
        enc.setBuffer(a.buffer, offset: a.offset, index: 1)
        enc.setBuffer(b.buffer, offset: b.offset, index: 2)
        enc.setBuffer(c.buffer, offset: c.offset, index: 3)
        enc.setBuffer(dt.buffer, offset: dt.offset, index: 4)
        enc.setBuffer(h.buffer, offset: h.offset, index: 5)
        enc.setBuffer(y.buffer, offset: y.offset, index: 6)
        var headDimV = UInt32(headDim)
        enc.setBytes(&headDimV, length: 4, index: 7)
        var stateDimV = UInt32(stateDim)
        enc.setBytes(&stateDimV, length: 4, index: 8)
        var headsPerGroupV = UInt32(headsPerGroup)
        enc.setBytes(&headsPerGroupV, length: 4, index: 9)
        let n = nHeads * headDim
        let tg = MTLSize(width: min(256, n), height: 1, depth: 1)
        let grid = MTLSize(width: n, height: 1, depth: 1)
        enc.dispatchThreads(grid, threadsPerThreadgroup: tg)
        enc.endEncoding()
    }
}
