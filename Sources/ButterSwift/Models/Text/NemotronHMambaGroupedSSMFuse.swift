// F-130: collapse `NemotronHMambaLayer.decode`'s 8x per-group `Ops.
// ssmStep` dispatch loop (`n_groups=8` on every published NemotronH
// checkpoint) into ONE dispatch covering all heads/groups at once.
//
// `Ops.ssmStep` wraps the shipped `iron_ssm_step<T>` kernel — one
// thread per `(head, channel)`, single-group only. `NemotronHMambaLayer.
// decode` calls it once per group (see `NemotronHText.swift`'s F-129
// header note: "8x grouped ssmStep ... not collapsible without a wider
// kernel rewrite, left alone per scope") because the stock kernel has
// no notion of a group — the host slices `a`/`dt`/`x`/`state`/`y` to a
// group's head sub-range and `b`/`c` to that group's flat `[state_dim]`
// row via `Tensor.offset`, then dispatches the single-group kernel at
// that offset. 8 dispatches/layer x 23 mamba layers = 184 of the
// model's ~900 decode-step dispatches — the single biggest block.
//
// This file adds a WIDER kernel that folds all 8 dispatches into one:
// same per-thread math as `iron_ssm_step` (see below), but the grid
// spans every `(head, channel)` pair across ALL heads at once, and
// each thread derives its own group index on-device
// (`head_id / heads_per_group`) to address the right slice of the
// FULL (unsliced) `b`/`c` buffers — replacing the host-side `Tensor.
// offset` slicing with an equivalent on-device index computation.
//
// Bit-exactness: every floating-point operation a thread performs is
// IDENTICAL in expression, order, and operand values to what
// `iron_ssm_step` computes for that same `(head, channel, state
// element)` triple in the unfused 8x-loop form — this is purely an
// address-computation change (an on-device `g_id * state_dim + n`
// integer index replacing a host-side buffer-offset add), not a
// numerical one. Concretely:
//   - `iron_ssm_step_f32.metal` (the "Generated by Iron" AOT shader,
//     see `Sources/IronSwift/Resources/kernels/iron_ssm_step_f32.
//     metal`) is transcribed here VERBATIM (same variable-per-step
//     structure, same cast points, same operand order — e.g.
//     `((v_dt_val * v_b_n) * v_x_d)`, matching `iron_ssm_step`'s Rust
//     source `dt_val * b_n * x_d` left-to-right) with only the `b`/`c`
//     index swapped from the implicit 0-based `i_0` (valid because the
//     stock per-group dispatch's `b`/`c` buffers were host-offset to
//     that group's row) to an explicit `bc_base + i_0` where
//     `bc_base = (head_id / heads_per_group) * state_dim` addresses
//     the SAME physical memory location in the full, unsliced `b`/`c`
//     buffers.
//   - `h`/`x`/`a`/`dt`/`y` addressing is the analogous change: the
//     per-call-local `h_id` (which indexed into an already-offset
//     per-group slice) becomes the GLOBAL head id (indexing the full
//     buffer directly) — again the same physical address, computed a
//     different way.
//   - `h` (state) stays fp32 throughout, matching `Ops.ssmStep`'s
//     precondition — the recurrence drifts in bf16/f16 within a few
//     dozen decode steps, and this state is recurrent across the
//     entire decode stream.
//
// Since no float operation's inputs, order, or count changes, the
// compiled instruction sequence per output element is expected to
// match `iron_ssm_step` bit-for-bit AS LONG AS the compile-time
// fast-math setting matches. Per `NemotronHMambaMixerFuse`'s header
// (the F-129 sibling fusion), iron's own AOT-compiled kernels build
// under Metal's DEFAULT fast-math (`fastMathEnabled = true`) — this
// file matches that. `NemotronHMambaGroupedSSMFuseTests` verifies
// strict bit-equality against the unfused 8x-loop reference across all
// three activation dtypes and a 32-step recurrence (state carries
// across steps, so any drift would compound and must be caught before
// it does).
//
// Kernel packaging: same "always live-compile via `makeLibrary
// (source:)`, never AOT-registered" choice as `NemotronHMambaMixerFuse`
// — see that file's header for why (independent `fastMathEnabled` per
// fusion, not the AOT overlay path).

import Foundation
import Metal
import IronSwift

enum NemotronHMambaGroupedSSMFuse {
    /// Default ON — verified bit-identical to the unfused 8x-loop
    /// `Ops.ssmStep` chain across f32/f16/bf16 and a 32-step
    /// recurrence (`NemotronHMambaGroupedSSMFuseTests`), and faster
    /// (1 dispatch/layer instead of 8). `BUTTER_NEMOTRON_SSM_GROUPED=0`
    /// reverts to the original per-group loop byte-for-byte.
    static let enabled: Bool =
        ButterEnv["BUTTER_NEMOTRON_SSM_GROUPED"] != "0"

    nonisolated(unsafe) private static var psoCache: [String: MTLComputePipelineState] = [:]
    private static let lock = NSLock()

    private static func pso(
        _ name: String, source: String, device: MTLDevice, fastMath: Bool
    ) -> MTLComputePipelineState {
        lock.lock(); defer { lock.unlock() }
        let cacheKey = fastMath ? name : "\(name)#strict"
        if let p = psoCache[cacheKey] { return p }
        let opts = MTLCompileOptions()
        opts.fastMathEnabled = fastMath
        let lib = try! device.makeLibrary(source: source, options: opts)
        let fn = lib.makeFunction(name: name)!
        let p = try! device.makeComputePipelineState(function: fn)
        psoCache[cacheKey] = p
        return p
    }

    // Transcribed verbatim from `iron_ssm_step_{f32,f16,bf16}.metal`
    // (see file header) with only the `b`/`c` index widened from the
    // implicit per-group-offset `i_0` to an explicit `bc_base + i_0`,
    // and `gid.x` now ranging over ALL heads instead of one group's
    // head sub-range. `h` is always fp32 in every dtype variant,
    // matching the stock kernel.
    private static let ssmStepGroupedSrc = """
    #include <metal_stdlib>
    using namespace metal;

    kernel void nemotron_mixer_ssm_step_grouped_f32(
        const device float *x [[buffer(0)]],
        const device float *a [[buffer(1)]],
        const device float *b [[buffer(2)]],
        const device float *c [[buffer(3)]],
        const device float *dt [[buffer(4)]],
        device float *h [[buffer(5)]],
        device float *y [[buffer(6)]],
        constant uint &head_dim [[buffer(7)]],
        constant uint &state_dim [[buffer(8)]],
        constant uint &heads_per_group [[buffer(9)]],
        uint3 gid [[thread_position_in_grid]]
    ) {
        uint v_idx = gid.x;
        auto v1 = head_dim;
        auto v_h_id = v_idx / v1;
        auto v3 = v_h_id * v1;
        auto v_d = v_idx - v3;
        auto v5 = dt[v_h_id];
        float v_dt_val = static_cast<float>(v5);
        auto v7 = a[v_h_id];
        auto v9 = (static_cast<float>(v7) * v_dt_val);
        auto v_decay = exp(v9);
        auto v12 = v3 + v_d;
        auto v13 = x[v12];
        float v_x_d = static_cast<float>(v13);
        auto v15 = 0.0f;
        auto __ml_y_d = v15;
        auto v16 = state_dim;
        auto v17 = v_h_id * v16;
        auto v_h_base = v17 * v1;
        auto v_g_id = v_h_id / heads_per_group;
        auto v_bc_base = v_g_id * v16;
        uint v20 = 1u;
        uint v19 = 0u;
        for (uint i_0 = v19; i_0 < v16; i_0 += v20) {
            auto v21 = i_0 * v1;
            auto v_h_idx = ((v_h_base + v21) + v_d);
            auto v_h_old = h[v_h_idx];
            auto v_bc_idx = v_bc_base + i_0;
            auto v25 = b[v_bc_idx];
            float v_b_n = static_cast<float>(v25);
            auto v29 = ((v_dt_val * v_b_n) * v_x_d);
            auto v_new_h = ((v_decay * v_h_old) + v29);
            h[v_h_idx] = v_new_h;
            auto v31 = c[v_bc_idx];
            auto v33 = __ml_y_d;
            auto v34 = (static_cast<float>(v31) * v_new_h);
            auto v35 = v33 + v34;
            __ml_y_d = v35;
        }
        auto v38 = __ml_y_d;
        float v39 = static_cast<float>(v38);
        auto v37 = v3 + v_d;
        y[v37] = v39;
    }

    kernel void nemotron_mixer_ssm_step_grouped_f16(
        const device half *x [[buffer(0)]],
        const device half *a [[buffer(1)]],
        const device half *b [[buffer(2)]],
