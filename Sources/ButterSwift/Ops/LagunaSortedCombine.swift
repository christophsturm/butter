// F-85 prefill pack, item 4: sorted-MoE combine fusion.
//
// MoELayer's default prefill MoE tail (T31: `tail` 2.3% + `sort` 3.4% of
// the whole-prefill wall) already does most of what this item asks for via
// two existing generated kernels (`Ops.moeSortPlan` / `Ops.moeUnpermute`,
// wired at `MoELayer.decodeManyNvfp4`'s "route"/"tail" checkpoints, see
// benchmarks/laguna-xs/README.md T25/T31):
//   - `Ops.moeSortPlan` already builds `sortedExperts`/`sourceTokens`/
//     `invPerm` in ONE device-side dispatch (`iron_moe_sort_plan_f32`).
//     There is no second argsort to replace in this call site; `invPerm`
//     is not derived from a second sort of `sourceTokens`, it's written
//     directly by the same pass that produces the sort itself.
//   - `Ops.moeUnpermute` already reads `downOut` (the down-proj output,
//     expert-sorted, `[mTotal, hidden]`) DIRECTLY, no separate unsorted
//     intermediate is materialized before the weighted top-k sum; `downOut`
//     itself is the buffer the mission's "~16MB intermediate" arithmetic
//     matches (mTotal=4096, hidden=2048, bf16 -> 16,777,216 bytes), and it
//     is unavoidable (it's the down-proj GEMM's own output), not an extra
//     copy this fusion could remove.
//
// Both `iron_moe_sort_plan_f32` and `iron_moe_unpermute_*` are generated by
// the sibling `iron` DSL repo (`make regenerate-kernels`), their .metal
// source is not checked into this repo (compiled offline into
// `kernels.metallib`, a build artifact, not tracked in git), so this
// session has no visibility into whether `iron_moe_unpermute_*`'s
// weight*value accumulation is FMA-contracted. The mission's own numerics
// note ("split the multiply and add (no fused contraction) or outputs
// mismatch ~half the elements") is exactly the class of bug that would be
// invisible without reading that generated source, which this session
// cannot do.
//
// What ships here instead: a hand-authored, self-contained (live-compiled
// from Swift string source, same pattern as `LagunaSdpa`'s kernels, no
// `iron`/codegen dependency) drop-in alternative to `Ops.moeUnpermute`,
// `LagunaSortedCombine.combine`, that explicitly separates the multiply
// from the add (products computed into a local array first, summed in a
// distinct second loop) AND compiles with `fastMathEnabled = false` so the
// Metal compiler cannot contract them back into an FMA. Also ships the
// `inverse[order[i]] = i` scatter the mission asks for
// (`LagunaSortedCombine.inversePermutation`) as reusable infra + the
// direct target of this file's "inverse-perm correctness vs argSort" test.
// Not wired into the default `moeSortPlan` path (which has no second
// argsort to remove, per above), but usable by any future sort primitive
// that only produces `order` (not `invPerm` directly).
//
// Opt-in: BUTTER_LAGUNA_SORTED_COMBINE=1 (default OFF, unverified this
// session, no build/test was run). Wired as a straight alternative to
// `Ops.moeUnpermute` at `MoELayer.decodeManyNvfp4`'s tail combine call
// site; default behavior (flag unset) is completely unchanged.

import Foundation
import Metal

enum LagunaSortedCombine {
    static var enabled: Bool {
        ButterEnv["BUTTER_LAGUNA_SORTED_COMBINE"] == "1"
    }

    nonisolated(unsafe) private static var psoCache: [String: MTLComputePipelineState] = [:]
    private static let lock = NSLock()

    private static func pso(_ name: String, source: String, device: MTLDevice)
        -> MTLComputePipelineState
    {
        lock.lock(); defer { lock.unlock() }
        if let p = psoCache[name] { return p }
        let opts = MTLCompileOptions()
        // CRITICAL (mission's own numerics note): disabling fast-math also
        // disables FP contraction, so `w*v` followed by `+=` cannot be
        // silently rewritten into a single `fma` by the Metal compiler.
        // The kernel source below already separates the two into distinct
        // loops as belt-and-suspenders; this is the second, compiler-level
        // guarantee.
        opts.fastMathEnabled = false
        let lib = try! device.makeLibrary(source: source, options: opts)
        let fn = lib.makeFunction(name: name)!
        let p = try! device.makeComputePipelineState(function: fn)
        psoCache[name] = p
        return p
    }

    // MARK: - inverse[order[i]] = i

    private static let inversePermSrc = """
    #include <metal_stdlib>
    using namespace metal;
    // inverse[order[i]] = i, one thread per source slot. `order` need not
    // be sorted, this is a plain scatter, not a sort.
    kernel void laguna_moe_inverse_perm_scatter_u32(
        device const uint *order [[buffer(0)]],
        device uint *inverse [[buffer(1)]],
        uint i [[thread_position_in_grid]]
    ) {
        inverse[order[i]] = i;
    }
    """

    /// `inverse[order[i]] = i` for `i` in `[0, mTotal)`. `order` is a
    /// permutation of `[0, mTotal)` (e.g. `sourceTokens` from a sort that
    /// only produced the forward order, not the inverse). One dispatch,
    /// device-side, no host readback, see file header for why the
    /// default `moeSortPlan` path doesn't need this (it already emits
    /// `invPerm` directly).
    static func inversePermutation(
        order: Tensor, into inverse: Tensor, mTotal: Int,
        on cmd: MTLCommandBuffer, device: Device
    ) {
        precondition(order.dtype == .u32, "inversePermutation: order must be u32")
        precondition(inverse.dtype == .u32, "inversePermutation: inverse must be u32")
        precondition(order.elementCount == mTotal && inverse.elementCount == mTotal)
        let p = pso(
            "laguna_moe_inverse_perm_scatter_u32", source: inversePermSrc,
            device: device.mtlDevice)
        guard let enc = cmd.makeComputeCommandEncoder() else { return }
        enc.setComputePipelineState(p)
        enc.setBuffer(order.buffer, offset: order.offset, index: 0)
        enc.setBuffer(inverse.buffer, offset: inverse.offset, index: 1)
        enc.dispatchThreads(
            MTLSize(width: mTotal, height: 1, depth: 1),
            threadsPerThreadgroup: MTLSize(width: min(mTotal, 256), height: 1, depth: 1))
        enc.endEncoding()
    }

    // MARK: - fused unsort + weight-multiply + top-k sum

    // `out[r][d] = sum_{s=0}^{k-1} weights[r*k+s] * expertOutputs[invPerm[r*k+s]][d]`.
    // Reads `expertOutputs` (`downOut`, expert-sorted order) directly, no
    // intermediate unsorted buffer. `k` is capped at 8 (Laguna's own
    // topK) by the fixed-size `prod` array, precondition-checked at the
    // Swift call site, not re-checked in-kernel.
    //
    // Numerics: `prod[s] = w * v` is written in a loop separate from the
    // `acc = acc + prod[s]` summation loop, and the pipeline is compiled
    // with `fastMathEnabled = false` (see `pso(_:source:device:)` above) so
    // the two cannot be contracted into a single `fma` by the compiler.
    private static func combineSource(elemType: String, castIn: String, castOut: String) -> String {
        """
        #include <metal_stdlib>
        using namespace metal;
        kernel void laguna_moe_sorted_combine_\(elemType)(
            device const \(elemType) *expert_outputs [[buffer(0)]],
            device const uint *inv_perm [[buffer(1)]],
            device const \(elemType) *top_k_weights [[buffer(2)]],
            device \(elemType) *out [[buffer(3)]],
            constant uint &hidden [[buffer(4)]],
            constant uint &k [[buffer(5)]],
            uint2 gid [[thread_position_in_grid]]
        ) {
            uint r = gid.x;
            uint d = gid.y;
            if (d >= hidden) return;
            float prod[8];
            for (uint s = 0; s < k; ++s) {
                uint slot = r * k + s;
                float w = \(castIn)(top_k_weights[slot]);
                uint sortedRow = inv_perm[slot];
                float v = \(castIn)(expert_outputs[sortedRow * hidden + d]);
                prod[s] = w * v;
            }
            float acc = 0.0f;
            for (uint s = 0; s < k; ++s) {
                acc = acc + prod[s];
            }
            out[r * hidden + d] = \(castOut)(acc);
        }
        """
    }

    private static let combineSrcBf16 = combineSource(
        elemType: "bfloat", castIn: "float", castOut: "bfloat")
    private static let combineSrcF16 = combineSource(
        elemType: "half", castIn: "float", castOut: "half")
    private static let combineSrcF32 = combineSource(
        elemType: "float", castIn: "float", castOut: "float")

    /// Drop-in alternative to `Ops.moeUnpermute` (same signature/contract).
    /// `k` must be <= 8 (fixed-size local accumulator in the kernel).
    static func combine(
        expertOutputs: Tensor,
        invPerm: Tensor,
        topKWeights: Tensor,
        into out: Tensor,
        nRows: Int, hidden: Int, k: Int,
        on cmd: MTLCommandBuffer, device: Device
    ) {
        precondition(k <= 8, "LagunaSortedCombine.combine: k=\(k) exceeds the 8-slot local accumulator")
        precondition(invPerm.dtype == .u32, "LagunaSortedCombine.combine: invPerm must be u32")
        precondition(
            expertOutputs.dtype == topKWeights.dtype && topKWeights.dtype == out.dtype,
            "LagunaSortedCombine.combine: expertOutputs/topKWeights/out must share dtype")
        precondition(expertOutputs.elementCount == nRows * k * hidden)
        precondition(invPerm.elementCount == nRows * k)
        precondition(topKWeights.elementCount == nRows * k)
        precondition(out.elementCount == nRows * hidden)

        let (name, source): (String, String)
        switch out.dtype {
        case .bf16: (name, source) = ("laguna_moe_sorted_combine_bfloat", combineSrcBf16)
        case .f16: (name, source) = ("laguna_moe_sorted_combine_half", combineSrcF16)
        case .f32: (name, source) = ("laguna_moe_sorted_combine_float", combineSrcF32)
        default:
            fatalError("LagunaSortedCombine.combine: unsupported dtype \(out.dtype)")
        }
        let p = pso(name, source: source, device: device.mtlDevice)
        guard let enc = cmd.makeComputeCommandEncoder() else { return }
        enc.setComputePipelineState(p)
        enc.setBuffer(expertOutputs.buffer, offset: expertOutputs.offset, index: 0)
        enc.setBuffer(invPerm.buffer, offset: invPerm.offset, index: 1)
        enc.setBuffer(topKWeights.buffer, offset: topKWeights.offset, index: 2)
        enc.setBuffer(out.buffer, offset: out.offset, index: 3)
        var hiddenU = UInt32(hidden)
        var kU = UInt32(k)
        enc.setBytes(&hiddenU, length: 4, index: 4)
        enc.setBytes(&kU, length: 4, index: 5)
        enc.dispatchThreads(
            MTLSize(width: nRows, height: hidden, depth: 1),
            threadsPerThreadgroup: MTLSize(width: 1, height: min(hidden, 256), depth: 1))
        enc.endEncoding()
    }
}
